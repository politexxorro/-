"""Full-res redraws of the pillow phases (sheet phases are too small for a mid shot)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'scripts'))
import api  # noqa: E402

R = 'shots/shot01/raw/'
HE = 'characters/reference/he_emotions.png'
BASE = ('Перерисуй ту же фазу анимации в полном разрешении. Сохрани парня полностью идентичным референсам: лицо, '
        'глаза, нос, причёска, чёлка, цвет кожи, чёрная олимпийка с серыми кантами, чёрная футболка, серебряная '
        'цепочка, стиль рисовки и толщина линий как на листе эмоций. Кадр: средний план сбоку на уровне кровати, он '
        'лежит на белой подушке под светлым одеялом; голова в левой трети кадра, одеяло уходит за правый край кадра, '
        'подушка уходит за левый край. {what} Ровно 5 пальцев. Не меняй причёску, одежду, цвета, форму лица, возраст, '
        'стиль, не добавляй аксессуаров. Прозрачный фон. Без надписей, без букв, без текста.')


def go(out, refs, what):
    if not Path(R + out).exists():
        print(api.edit(refs, BASE.format(what=what), R + out, size='1536x1024', background='transparent'))


if sys.argv[1] == 'k1':
    go('he_pillow_k1_v1.png', [R + 'he_pillow_p1.png', R + 'he_sleep_mid_v1.png', HE],
       'Поза и мимика строго как на первом изображении: сонная смущённая улыбка, глаза полуприкрыты, руки под одеялом.')
else:
    k1 = R + 'he_pillow_k1_v1.png'
    same = 'Положение головы, масштаб и кадрирование строго как на первом изображении. '
    go('he_pillow_k2_v1.png', [k1, R + 'he_pillow_p2.png', HE],
       same + 'Измени только позу как на втором изображении: правой рукой тянет вторую белую подушку к лицу, подушка '
              'на полпути, сонная улыбка, глаза полуприкрыты.')
    go('he_pillow_k3_v1.png', [k1, R + 'he_pillow_p3.png', HE],
       same + 'Измени только позу как на втором изображении: вторая белая подушка полностью закрывает лицо, его рука '
              'прижимает её, над подушкой видны его волосы.')
    go('he_pillow_k1_eyes_closed_v1.png', [k1, HE],
       'Повтори первое изображение пиксель в пиксель, измени ТОЛЬКО глаза: полностью закрыты (сонное моргание), как '
       'эмоция 6 на листе эмоций.')
